/*
    OPERATOR COMPARISON
    Digunakan untuk membandingkan nilai dan menghasilkan nilai boolean (true/false)

    >, >=, <, <=, ==, ===, !=, !==
*/

console.log(10 > 5); // true
console.log(10 >= 10); // true
console.log(5 < 10); // true
console.log(101 <= 101); // true

/*
    == dan ===

    ==  : Komparasi nilai saja
    === : Komparasi nilai dan tipe data
*/
console.log(5 == '5'); // true 
console.log(5 === '5'); // false

console.log(5 != '5'); // false
console.log(5 !== '5'); // true