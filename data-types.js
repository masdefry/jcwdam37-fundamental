/*
    DATA TYPES 

    1. Primitive Data Types:
        - Boolean
        - Number
        - String 
        - Undefined 
        - Null
*/

/* Boolean: Tipe data yang memiliki 2 nilai, yaitu true atau false */
var isGraduated = true;
var isPaid = false;
console.log(typeof isGraduated);
console.log(typeof isPaid);

/* String: Tipe data yang nilai nya dibungkus dengan '...', "...", `...` */
var text = 'Defryan';
var paragraph = 'Purwadhika Bootcamp';
console.log(typeof text);
console.log(typeof paragraph);

/* Number */
var discount = 0.75;
var point = 101;
console.log(typeof discount);
console.log(typeof point);

/* Undefined & Null */
var fullName;
var isEmpty = null;
console.log(typeof fullName);
console.log(typeof isEmpty);
