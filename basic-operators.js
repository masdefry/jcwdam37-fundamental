/*
    BASIC OPERATOR:
        +, -, *, /, %
*/
var number1 = 10;
var number2 = 5;
console.log(number1 + number2);
console.log(number1 - number2);
console.log(number1 * number2);
console.log(number1 / number2);

/* Modulus: Sisa bagi */
console.log(number1 % number2); // 10 % 5
console.log(6 % 4); // 2
console.log(8 % 5); // 3
